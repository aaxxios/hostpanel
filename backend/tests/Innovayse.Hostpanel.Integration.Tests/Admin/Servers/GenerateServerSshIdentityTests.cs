using System.Net;
using System.Net.Http.Json;
using System.Text;
using System.Text.Json;
using FluentAssertions;
using Innovayse.Hostpanel.Application.Common.Errors;
using Innovayse.Hostpanel.Application.Common.Interfaces;
using Innovayse.Hostpanel.Domain.Servers.Enums;
using Innovayse.Hostpanel.Integration.Tests.Fixtures;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using Renci.SshNet;
using Xunit;

namespace Innovayse.Hostpanel.Integration.Tests.Admin.Servers;

/// <summary><c>POST api/admin/servers/{id}/ssh-identity</c>: per-server ED25519 identities generated by HostPanel.</summary>
public sealed class GenerateServerSshIdentityTests(IntegrationTestFactory factory) : IClassFixture<IntegrationTestFactory>
{
    [Fact]
    public async Task Generate_ReturnsThePublicHalfOnly_AndStoresAUsablePrivateKeyAsync()
    {
        var admin = await SshAdminTestSupport.AdminAsync(factory);
        var serverId = await NewCwpServerAsync(admin);

        var response = await admin.PostAsync($"/api/admin/servers/{serverId}/ssh-identity", null);

        response.StatusCode.Should().Be(HttpStatusCode.OK);
        var raw = await response.Content.ReadAsStringAsync();
        raw.Should().NotContain("PRIVATE KEY");
        var body = JsonDocument.Parse(raw).RootElement;
        var publicKey = body.GetProperty("publicKey").GetString()!;
        publicKey.Should().StartWith("ssh-ed25519 ").And.EndWith($"hostpanel-server-{serverId}");
        body.GetProperty("profile").GetString().Should().Be("cwp");
        body.GetProperty("binding").GetGuid().Should().NotBeEmpty();

        // The stored private key is a real OpenSSH key whose public half is the one returned.
        using var scope = factory.Services.CreateScope();
        var stored = await scope.ServiceProvider.GetRequiredService<IHostpanelDbContext>()
            .ServerSshSettings.AsNoTracking().SingleAsync(s => s.ServerId == serverId);
        using var keyFile = new PrivateKeyFile(new MemoryStream(Encoding.UTF8.GetBytes(stored.AgentPrivateKey!)));
        var loaded = keyFile.Key.ToString();
        loaded.Should().Be("ssh-ed25519");
        stored.AgentPublicKey.Should().Be(publicKey);
    }

    [Fact]
    public async Task EachServerGetsItsOwnIdentity_AndRotationKeepsTheBindingAndDisablesAsync()
    {
        var admin = await SshAdminTestSupport.AdminAsync(factory);
        var a = await NewCwpServerAsync(admin);
        var b = await NewCwpServerAsync(admin);

        var first = await (await admin.PostAsync($"/api/admin/servers/{a}/ssh-identity", null)).Content.ReadFromJsonAsync<JsonElement>();
        var other = await (await admin.PostAsync($"/api/admin/servers/{b}/ssh-identity", null)).Content.ReadFromJsonAsync<JsonElement>();
        var rotated = await (await admin.PostAsync($"/api/admin/servers/{a}/ssh-identity", null)).Content.ReadFromJsonAsync<JsonElement>();

        other.GetProperty("publicKey").GetString().Should().NotBe(first.GetProperty("publicKey").GetString());
        other.GetProperty("binding").GetGuid().Should().NotBe(first.GetProperty("binding").GetGuid());
        rotated.GetProperty("publicKey").GetString().Should().NotBe(first.GetProperty("publicKey").GetString());
        rotated.GetProperty("binding").GetGuid().Should().Be(first.GetProperty("binding").GetGuid());
        var settings = await admin.GetFromJsonAsync<JsonElement>($"/api/admin/servers/{a}/ssh-settings");
        settings.GetProperty("isEnabled").GetBoolean().Should().BeFalse();
    }

    [Fact]
    public async Task UnsupportedModule_IsRefusedAsync()
    {
        var admin = await SshAdminTestSupport.AdminAsync(factory);
        var serverId = await SshTestSeeds.SeedServerAsync(factory, "panel.example.test", 22, ServerModule.CPanel, enabled: false);

        var response = await admin.PostAsync($"/api/admin/servers/{serverId}/ssh-identity", null);

        response.StatusCode.Should().Be(HttpStatusCode.BadRequest);
        (await DomainsTestSeeds.ReadErrorCodeAsync(response)).Should().Be(HostpanelErrorCodes.SSH_MODULE_NOT_SUPPORTED);
    }

    /// <summary>Creates a CWP server through the admin API, with no SSH settings yet.</summary>
    private static async Task<int> NewCwpServerAsync(HttpClient admin)
    {
        var created = await admin.PostAsJsonAsync("/api/admin/servers", new
        {
            name = $"ident-{Guid.NewGuid():N}", hostname = "ident.example.test", module = ServerModule.Cwp7, username = "root",
        });
        created.EnsureSuccessStatusCode();
        return await created.Content.ReadFromJsonAsync<int>();
    }
}
