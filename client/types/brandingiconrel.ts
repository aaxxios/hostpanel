/**
 * The `rel` values the storefront's favicon links use; the strings are the HTML link relations.
 *
 * @module types/brandingiconrel
 */
export enum BrandingIconRel {
  /** A browser tab, shortcut or Android home-screen icon. */
  Icon = 'icon',
  /** The icon iOS puts on a home screen. */
  AppleTouchIcon = 'apple-touch-icon'
}
