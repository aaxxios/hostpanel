/**
 * Every template the portal can render; the values are what the `portal.template` setting holds.
 *
 * @module types/templatename
 */
export enum TemplateName {
  /** The shipped default design. */
  Aurora = 'aurora',
  /** The second design. */
  Nova = 'nova',
  /** The dark-only classic design. */
  Classic = 'classic'
}
